// 부스 데이터에 섞여 들어오는 "남의 목소리"를 가려낸다.
//
// 왜 필요한가: `enrichment.summary`는 전시마다 출처가 다르다. SIBF·하우스 아카이브는
// 운영자가 쓴 공식 소개라 로미가 자기 말처럼 인용해도 되지만, SIF는 참가 작가가 직접 쓴
// 자기소개(`links-sif-2026.json`의 intro)가 그대로 들어온다. 그 글은 **작가가 1인칭
// 존댓말로 자기를 소개**하는 글이라, 로미의 사실 절 자리에 그대로 넣으면 화자가 뒤집힌다.
//
//   로미가 말해야 하는 자리에 → "안녕하세요! 순간을 기록하는 423희희입니다"
//
// 809개 중 134개(16.6%)가 이 상태였고, 일부는 판매 홍보까지 섞여 있었다
// ("교보문고 판매중", "맹수만 판매합니다"). 브랜드북 §1-1(반말)·§1-3(1인칭)·§1-4(영업
// 금지) 동시 위반인데, 사전이 아니라 **데이터**로 들어오는 경로라 brand-voice 테스트로는
// 잡히지 않는다. 그래서 읽는 쪽에서 가려낸다.
//
// 왜 고쳐 쓰지 않고 인용하는가: 남이 쓴 글을 반말로 바꾸는 건 남의 말을 바꾸는 것이다.
// `booth/about.ts`가 같은 이유로 이미 인용 분리를 택했다 — 여기서 그 판단을 공유한다.
//
// 감사 근거: `docs/qa/2026-08-15_grounding-audit.md` 발견 2.

/** 문장이 존댓말로 끝나는가 — 로미는 반말이므로 이건 로미의 말이 아니다. */
const HONORIFIC = /(습니다|입니다|합니다|됩니다|해요|예요|이에요|드립니다|주세요|하세요)/;

/** 자기소개의 인사말 — 화자가 부스 당사자라는 가장 확실한 신호. */
const GREETING = /(안녕하세요|반갑습니다|처음\s*뵙|어서\s*오세요)/;

/** 판매·홍보 문구. 로미는 영업하지 않는다(브랜드북 §1-4). */
const SALES =
  /(판매\s*(중|합니다|해요)|구매\s*(하|해|가능)|주문\s*(제작|가능|하)|교보문고|예약\s*판매|스토어\s*(오픈|링크)|DM\s*(주세요|❌|X)|문의\s*주세요|팔로우)/;

/**
 * 이 텍스트가 **로미가 아닌 사람의 말**인지.
 *
 * true면 로미의 사실 절로 쓰지 않고 출처를 밝혀 인용한다.
 * false여도 "로미가 쓴 글"이라는 뜻은 아니다 — "다꾸러가 만드는 다꾸용 다이어리" 같은
 * 명사구는 화자가 드러나지 않아 로미가 인용해도 목소리가 깨지지 않는다.
 * 여기서 거르는 건 **화자가 눈에 보이는 글**뿐이다.
 */
export function isSomeoneElsesVoice(text?: string | null): boolean {
  const t = text?.trim();
  if (!t) return false;
  return HONORIFIC.test(t) || GREETING.test(t) || SALES.test(t);
}

#!/usr/bin/env node
// 디자인 시스템 v2 웹 산출물을 Roam-design의 **고정한 커밋**에서 그대로 복사한다.
//
//   npm run tokens:sync            source.json의 commit에서 받아 src/styles/v2/에 쓰고 sha256을 적는다
//   npm run tokens:check           받은 파일과 레포 사본을 바이트까지 비교한다(쓰지 않는다)
//   npm run tokens:sync -- --commit <sha>   고정 커밋을 바꾸고 받는다
//
// 원천을 찾는 순서:
//   1) ROAM_DESIGN_DIR 환경 변수(로컬 Roam-design 체크아웃)
//   2) 이 레포 옆의 ../Roam-design(worktree여도 메인 체크아웃 기준으로 찾는다)
//   3) gh api(비공개 레포라 gh 로그인이 필요하다)
// 어느 길이든 **커밋으로** 읽는다. 작업 폴더의 고치던 파일은 읽지 않는다.
//
// 결정: Roam-design docs/decisions/2026-11-18_v2-토큰-Swift-생성.md "Roam 웹이 받는 방법",
//       Roam docs/decisions/2026-11-18_웹-디자인-v2-이전-계획.md
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "src/styles/v2/source.json");

export function sha256(buf) {
  return createHash("sha256").update(buf).digest("hex");
}

/**
 * tokens.css의 라이트(:root) 블록에서 길이 토큰만 숫자(px)로 뽑는다. SVG 지도처럼 CSS 변수를
 * 숫자로 계산해야 하는 자리가 쓴다. 손으로 적은 값이 아니라 복사한 CSS에서 기계로 나온 값이고,
 * 검사(v2-tokens.test.ts)가 같은 함수로 다시 뽑아 파일과 맞대 본다.
 */
export function deriveLengths(css) {
  const root = css.match(/:root\s*\{([\s\S]*?)\n\}/);
  if (!root) throw new Error("tokens.css에 :root 블록이 없어요");
  const vars = new Map();
  for (const m of root[1].matchAll(/--roam-v2-([a-z0-9-]+):\s*([^;]+);/g)) vars.set(m[1], m[2].trim());
  const resolve = (v, depth = 0) => {
    const ref = v.match(/^var\(--roam-v2-([a-z0-9-]+)\)$/);
    if (ref && depth < 8) return vars.has(ref[1]) ? resolve(vars.get(ref[1]), depth + 1) : null;
    const px = v.match(/^(-?[0-9.]+)px$/);
    if (px) return Number(px[1]);
    const rem = v.match(/^(-?[0-9.]+)rem$/);
    if (rem) return Number(rem[1]) * 16;
    return null;
  };
  const out = {};
  for (const [k, v] of vars) {
    const n = resolve(v);
    if (n !== null) out[k] = n;
  }
  return out;
}

export function lengthsModule(css) {
  const lengths = deriveLengths(css);
  const body = Object.entries(lengths)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`)
    .join("\n");
  return [
    "// Generated by scripts/tokens-sync.mjs from src/styles/v2/tokens.css — DO NOT EDIT.",
    "// v2 길이 토큰(라이트 :root)을 px 숫자로. SVG처럼 숫자 계산이 필요한 자리만 쓴다.",
    "// 화면 코드는 되도록 Tailwind -v2- 이름이나 var(--roam-v2-*)를 쓴다.",
    "export const V2_PX = {",
    body,
    "} as const;",
    "export type V2PxToken = keyof typeof V2_PX;",
    "",
  ].join("\n");
}

const LENGTHS_TS = "src/styles/v2/lengths.generated.ts";

function designDirCandidates() {
  const out = [];
  if (process.env.ROAM_DESIGN_DIR) out.push(resolve(process.env.ROAM_DESIGN_DIR));
  try {
    // worktree 안에서도 메인 체크아웃(.git이 있는 곳) 옆을 본다.
    const common = execFileSync("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], {
      cwd: ROOT,
      encoding: "utf8",
    }).trim();
    out.push(resolve(dirname(common), "../Roam-design"));
  } catch {
    /* git이 없으면 건너뛴다 */
  }
  out.push(resolve(ROOT, "../Roam-design"));
  return [...new Set(out)];
}

/** 고정 커밋의 파일 하나를 바이트로 읽는다. 못 읽으면 null. */
export function readPinned(repo, commit, path) {
  for (const dir of designDirCandidates()) {
    if (!existsSync(join(dir, ".git"))) continue;
    try {
      return execFileSync("git", ["-C", dir, "show", `${commit}:${path}`], {
        maxBuffer: 16 * 1024 * 1024,
        stdio: ["ignore", "pipe", "ignore"],
      });
    } catch {
      // 커밋이 아직 없는 로컬 사본일 수 있다 — 다음 길로.
    }
  }
  try {
    return execFileSync(
      "gh",
      ["api", "-H", "Accept: application/vnd.github.raw", `repos/${repo}/contents/${path}?ref=${commit}`],
      { maxBuffer: 16 * 1024 * 1024, stdio: ["ignore", "pipe", "ignore"] },
    );
  } catch {
    return null;
  }
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const ci = args.indexOf("--commit");
  const source = JSON.parse(readFileSync(SOURCE, "utf8"));
  if (ci !== -1) {
    const next = args[ci + 1];
    if (!/^[0-9a-f]{40}$/.test(next ?? "")) {
      console.error("--commit 에는 40자리 커밋 해시를 준다(브랜치 이름 금지 — 고정이 목적이다).");
      process.exit(2);
    }
    source.commit = next;
  }

  let bad = 0;
  for (const f of source.files) {
    const upstream = readPinned(source.repo, source.commit, f.from);
    if (!upstream) {
      console.error(`✗ ${f.from}@${source.commit.slice(0, 7)} 을 읽지 못했어요. ROAM_DESIGN_DIR 또는 gh 로그인을 확인해 주세요.`);
      process.exit(2);
    }
    const target = join(ROOT, f.to);
    const local = existsSync(target) ? readFileSync(target) : null;
    const same = local !== null && Buffer.compare(local, upstream) === 0;
    if (check) {
      if (!same) {
        bad++;
        console.error(`✗ ${f.to} 이 Roam-design ${source.commit.slice(0, 7)}:${f.from} 과 달라요. npm run tokens:sync`);
      } else if (f.sha256 !== sha256(upstream)) {
        bad++;
        console.error(`✗ source.json의 ${f.to} sha256이 낡았어요. npm run tokens:sync`);
      } else {
        console.log(`✓ ${f.to}`);
      }
      continue;
    }
    writeFileSync(target, upstream);
    f.sha256 = sha256(upstream);
    console.log(`${same ? "=" : "↻"} ${f.to}  ← ${source.commit.slice(0, 7)}:${f.from}`);
  }
  const tokensCss = readFileSync(join(ROOT, "src/styles/v2/tokens.css"), "utf8");
  const mod = lengthsModule(tokensCss);
  const lengthsPath = join(ROOT, LENGTHS_TS);
  if (check) {
    if (!existsSync(lengthsPath) || readFileSync(lengthsPath, "utf8") !== mod) {
      bad++;
      console.error(`✗ ${LENGTHS_TS} 이 tokens.css에서 뽑은 값과 달라요. npm run tokens:sync`);
    } else console.log(`✓ ${LENGTHS_TS}`);
    process.exit(bad ? 1 : 0);
  }
  writeFileSync(lengthsPath, mod);
  console.log(`↻ ${LENGTHS_TS}`);
  writeFileSync(SOURCE, JSON.stringify(source, null, 2) + "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
